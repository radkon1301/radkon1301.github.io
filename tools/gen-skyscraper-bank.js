// tools/gen-skyscraper-bank.js — offline builder for js/zapn/skyscraper-bank.js
// Run: node tools/gen-skyscraper-bank.js        (takes ~20 s; output is committed, nothing runs at page load)
// This is the SINGLE source of truth for the level table: edit LEVELS here, rerun, commit the output.
const fs = require('fs'), vm = require('vm'), path = require('path');

const LEVELS = [[4,5],[4,6],[4,7],[5,7],[5,9],[5,11],[6,10],[6,13],[7,14],[7,16]];   // [nBlocks, minOptimal]
const PER_LEVEL = 40;                                                                 // verified puzzles stored per level

const ctx = { Math, Float64Array, Uint8Array, Set, Array };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(__dirname, '../js/zapn/skyscraper-gen.js'), 'utf8') +
  '\nglobalThis.gen = skyGeneratePuzzle;', ctx);

const enc = p => p.map(x => x.join('')).join('|');   // block ids are single digits (n <= 7): "01|2|345"
const levels = LEVELS.map(([n, minOpt]) => {
  const seen = new Set(), puzzles = [];
  while (puzzles.length < PER_LEVEL) {
    const pz = ctx.gen(n, minOpt);
    if (pz.optimal < minOpt) continue;                 // generator fallback; never store an easier-than-promised puzzle
    const e = [enc(pz.start), enc(pz.target), pz.optimal], k = e[0] + '>' + e[1];
    if (seen.has(k)) continue;
    seen.add(k); puzzles.push(e);
  }
  console.log(`level n=${n} min=${minOpt}: ${puzzles.length} puzzles, optimal ${Math.min(...puzzles.map(p => p[2]))}-${Math.max(...puzzles.map(p => p[2]))}`);
  return `  {n:${n}, minOpt:${minOpt}, puzzles:[\n${puzzles.map(p => `    ${JSON.stringify(p)}`).join(',\n')}\n  ]}`;
});

fs.writeFileSync(path.join(__dirname, '../js/zapn/skyscraper-bank.js'),
`// js/zapn/skyscraper-bank.js — GENERATED by tools/gen-skyscraper-bank.js; do not edit by hand.
// Pre-solved Skyscraper puzzles: one entry per level = {n: blocks, minOpt: min optimal moves, puzzles: [[start, target, optimal], …]}.
// Piles are "|"-separated, blocks are single-digit ids bottom→top ("01|2|" = pile0 [0,1], pile1 [2], pile2 []).
// Runtime (skyPuzzleFromBank in skyscraper-gen.js) randomly relabels blocks and permutes piles, which preserves the optimal
// move count, so every play looks different with zero computation. Docs: docs/zapn.md
const SKY_BANK = [
${levels.join(',\n')}
];
`);
